    fun metaFor(productId: Int, defaultUnit: String): ProductMetaV3 {
        val raw = BY_ID[productId]
        val stepMode = resolveStepMode(productId, defaultUnit)
        return if (raw != null) {
            ProductMetaV3(
                shapeCode = raw.shape,
                colorCode = raw.color,
                sizeRank = raw.size,
                weightRank = raw.weight,
                searchKeywords = raw.kw,
                isPerishable = raw.perish,
                defBundleMilli = raw.bundle,
                unitStepMode = stepMode
            )
        } else {
            ProductMetaV3(
                shapeCode = "ROUND",
                colorCode = "GREEN",
                sizeRank = 2,
                weightRank = 2,
                searchKeywords = "",
                isPerishable = false,
                defBundleMilli = if (defaultUnit == "kg") 250L else 1000L,
                unitStepMode = stepMode
            )
        }
